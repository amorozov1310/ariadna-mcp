"""
Общее правило «присвоено не-модуль» (Этап 7, остаток).

После частных регулярок (Новый, цепочки, фабрики, индексация, менеджеры,
реквизиты формы) в топе нерезолвленных на реальной ERP остались переменные,
которым присвоено значение иной формы: результат функции с цепочкой
(`МакетСоставаПоказателей = ОбъектОтчета(...).ПолучитьМакет(...)`),
цепочка свойств без скобок (`ТекущиеДанные = Элементы.Товары.ТекущиеДанные`),
вызов платформенной функции (`ПолучитьФорму(...)`), копия другого имени
(`ТабДок = ПолеТабличногоДокументаФормаОтчета`) и т.п.

Ссылку на общий модуль переменная получает только из голого имени модуля
или загрузчика (ОбщийМодуль(...), Вычислить(...)); всё остальное — значение.
Правило никогда не помечает переменную с именем из known_modules, поэтому
вызовы, которые резолвятся к настоящим модулям, затронуть не может.
"""

import sys
import tempfile
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent.parent))

from src.core.bsl_parser import BSLParser
from src.core.db import Database
from src.core.indexer import Indexer

KNOWN = {'общегоназначения', 'управлениепечатью', 'common'}


def _calls(code: str, known_modules=KNOWN, **kw) -> set[tuple[str, str]]:
    result = BSLParser(known_modules=known_modules).parse(code, **kw)
    return {(c.callee_module, c.callee_proc) for c in result.calls}


