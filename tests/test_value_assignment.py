def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8-sig')


def test_indexer_keeps_real_calls_resolved_and_drops_phantoms():
    with tempfile.TemporaryDirectory() as tmpdir:
        xml_dir = Path(tmpdir) / 'xml'
        _write(xml_dir / 'CommonModules' / 'ОбщегоНазначения' / 'Ext' / 'Module.bsl', '''
Функция ОбщийМодуль(Имя) Экспорт
	Возврат Вычислить(Имя);
КонецФункции

Процедура СообщитьПользователю(Текст) Экспорт
КонецПроцедуры
''')
        _write(xml_dir / 'CommonModules' / 'УправлениеПечатью' / 'Ext' / 'Module.bsl', '''
Процедура Напечатать() Экспорт
КонецПроцедуры
''')
        _write(xml_dir / 'Reports' / 'Регламентированный' / 'Forms' / 'ФормаОтчета'
               / 'Ext' / 'Form' / 'Module.bsl', '''
&НаСервере
Процедура Сформировать()
	МакетСоставаПоказателей = ОбъектОтчета(ЭтаФормаИмя).ПолучитьМакет("Состав");
	МакетСоставаПоказателей.Область("R1C1");
	ТабДок = ПолеТабличногоДокументаФормаОтчета;
	ТабДок.Вывести(МакетСоставаПоказателей);
	Для Каждого Строка Из Таблица Цикл
		Строка.Заполнить();
	КонецЦикла;
	ОбщегоНазначения.СообщитьПользователю("готово");
	Модуль = ОбщегоНазначения.ОбщийМодуль("УправлениеПечатью");
	Модуль.Напечатать();
	Печать = УправлениеПечатью;
	Печать.Напечатать();
КонецПроцедуры
''')
        db = Database(str(Path(tmpdir) / 'index.db'))
        db.connect()
        db.init_schema()
        try:
            known_modules, known_objects = Indexer.scan_known_names([str(xml_dir)])
            indexer = Indexer(db)
            indexer.index_bsl(str(xml_dir), source_id='main',
                              known_modules=known_modules, known_objects=known_objects)
            indexer.resolve_calls()
            rows = db.conn.execute("""
                SELECT c.callee_module, c.callee_proc, c.callee_kind, cr.callee_id
                FROM calls c LEFT JOIN calls_resolved cr ON cr.call_id = c.id
            """).fetchall()
            module_calls = [(r['callee_module'], r['callee_proc'], bool(r['callee_id']))
                            for r in rows if r['callee_kind'] == 'common_module']
            assert sorted(module_calls) == sorted([
                ('ОбщегоНазначения', 'ОбщийМодуль', True),
                ('ОбщегоНазначения', 'СообщитьПользователю', True),
                ('УправлениеПечатью', 'Напечатать', True),
                ('УправлениеПечатью', 'Напечатать', True),
            ]), module_calls
        finally:
            db.close()


