def test_real_erp_shapes_are_values():
    code = '''
&НаСервере
Процедура Сформировать()
	МакетСоставаПоказателей = ОбъектОтчета(ЭтаФормаИмя).ПолучитьМакет("Состав");
	МакетСоставаПоказателей.Область("R1C1");
	ТекущиеДанные = Элементы.Товары.ТекущиеДанные;
	ТекущиеДанные.ПолучитьЭлементы();
	ФормаВыгрузкиРеглОтчета = ПолучитьФорму("Документ.ВыгрузкаРегламентированныхОтчетов.Форма");
	ФормаВыгрузкиРеглОтчета.Открыть();
	ТабДок = ПолеТабличногоДокументаФормаОтчета;
	ТабДок.Вывести(Область);
	ПечФорма = Макет.Получитьобласть("Титульный");
	ПечФорма.Заполнить(Данные);
КонецПроцедуры
'''
    calls = _calls(code)
    for phantom in ('МакетСоставаПоказателей', 'ТекущиеДанные', 'ФормаВыгрузкиРеглОтчета',
                    'ТабДок', 'ПечФорма'):
        assert not any(m == phantom for m, _ in calls), (phantom, calls)


