def test_call_with_arguments_on_next_lines_is_a_value():
    """Реальная ERP (379 вызовов): скобка вызова на строке присваивания
    открылась, но не закрылась. Уже этого факта достаточно — справа
    результат вызова, аргументы разбирать не нужно."""
    code = '''
&НаКлиенте
Процедура Выгрузить()
	ФормаВыгрузкиРеглОтчета = ПолучитьФорму(
		"Документ.ВыгрузкаРегламентированныхОтчетов.Форма.ФормаДокумента",
		Новый Структура("Ключ", Ссылка));
	ФормаВыгрузкиРеглОтчета.Проверить();
	ФормаВыгрузкиРеглОтчета.СформироватьИЗаписать();
	Значение = ОбщегоНазначения.ЗначениеРеквизитаОбъекта(Ссылка,
		"Организация");
	Значение.Заполнить();
	Данные = Объект.Получить(ОбщегоНазначения,
		УправлениеПечатью);
	Данные.Обработать();
	Result = GetForm("Catalog.Items.ListForm",
		Parameters);
	Result.Open2();
КонецПроцедуры
'''
    calls = _calls(code)
    for phantom in ('ФормаВыгрузкиРеглОтчета', 'Значение', 'Данные', 'Result'):
        assert not any(m == phantom for m, _ in calls), (phantom, calls)
    # Вызов настоящего модуля в правой части остаётся вызовом.
    assert ('ОбщегоНазначения', 'ЗначениеРеквизитаОбъекта') in calls, calls


