def test_real_modules_aliases_and_loaders_unchanged():
    code = '''
Процедура Тест()
	ОбщегоНазначения.СообщитьПользователю("текст");
	МодульА = УправлениеПечатью;
	МодульА.Напечатать();
	МодульБ = МодульА;
	МодульБ.Напечатать();
	МодульВ = ОбщегоНазначения.ОбщийМодуль("УправлениеПечатью");
	МодульВ.Напечатать();
	МодульГ = ОбщийМодуль("УправлениеПечатью");
	МодульГ.Напечатать();
	МодульД = Вычислить("УправлениеПечатью");
	МодульД.Напечатать();
КонецПроцедуры
'''
    calls = _calls(code)
    assert ('ОбщегоНазначения', 'СообщитьПользователю') in calls
    assert ('УправлениеПечатью', 'Напечатать') in calls
    # Алиасы резолвятся в модуль, а не пропадают.
    assert not any(m in ('МодульА', 'МодульБ', 'МодульВ') for m, _ in calls), calls
    # Загрузчики, которые парсер не разворачивает, остаются вызовами.
    assert ('МодульГ', 'Напечатать') in calls, calls
    assert ('МодульД', 'Напечатать') in calls, calls


